"""Employees dataset adapter — 99 QA tasks.

Tasks live in ``tasks.json`` (generated by
``scripts/generate_employees_questions.py`` against a pristine DB, golds
computed via the live API). All questions are read-only and answerable
through argument-side expressiveness — the EAG constraint by construction.
The set optimizes for baseline difficulty (~80-85% on glm-5.3-flash):
trap-dense composition — strict-inequality/period-inclusive boundary
traps over populated boundaries (naive filters provably differ), stacked
and senior-title/decade complement exclusions, stated/entity-referenced/
double disambiguation, near-miss comparisons with strict-date booleans,
derived-threshold chains, and reduced-volume EAG-discriminative
categories. Employees results older than 2026-09-14 predate the current
question set — don't mix them into rollups.

Scoring:
- numeric golds: the answer must contain exactly ONE distinct number and it
  must match the gold within 0.01 (first-number-anywhere and verbose
  answers with extra numbers are rejected); score = EM (0/1)
- ``true``/``false`` golds: canonical EM after normalize_answer (whole
  answer); F1 is boolean-strict (partial credit impossible)
- everything else (names, dates, titles, departments): correct = EM,
  score = F1 after canonical normalization — no substring passes

The system prompt is mode-aware: ``make_tools`` records the mode on the
instance (the runner always calls it before reading ``system_prompt``), so
baseline and EAG runs get appropriately-worded instructions without any
runner change.
"""

import json
import re
from pathlib import Path
from typing import Optional

from benchmarks.base import DatasetABC, Task
from benchmarks.registry import register
from metrics.em_f1 import exact_match, f1_score, normalize_answer
from tools.employees import make_employees_tools

_TASKS_PATH = Path(__file__).resolve().parent / "tasks.json"

_BASE_PROMPT = """\
You are an HR assistant with tools over the employees database API.

## Tools
- get_reference: valid titles and department numbers/names.
- search_employees: find employees by name parts (first_name AND last_name
  narrow to a unique candidate) plus filters (dept, title, gender, salary
  range, hire window, point-in-time active_at).
- get_employee / get_salary_history / get_title_history /
  get_department_history: per-employee current state and temporal records
  (default current; at_date or from_date/to_date for history).
- get_department / get_department_employees / get_department_managers:
  department detail, members, manager history.
- get_salary_stats / get_headcount / get_top_earners /
  get_salary_distribution: aggregates (server-side computed).
- compare / compute / concat / count_items / filter_items: local compute
  over prior results (comparisons, arithmetic, string joins, list counts,
  filtered selection).
- submit_answer: submit your final answer, then reply with a brief text.

## Rules
- To identify a person, search with first_name AND last_name until exactly
  one candidate remains. When several employees share a name, use the
  question's qualifier (department, title, gender) as an extra search
  filter until exactly one candidate remains.
- "How many" questions are answered by a server-computed count: the
  `total` field of a filtered search_employees call, or the `count` /
  `headcount` fields from the stats tools. NEVER enumerate employees one
  by one to count them.
- Questions combining two retrieved values — differences ("how much
  more"), sums, exclusions ("how many ... do NOT ..."), percentages, or
  comparisons — have no single-tool answer: fetch BOTH values, then use
  compute / compare over them. Never guess or estimate such answers.
- Titles are exact values (e.g. "Engineer" does not match
  "Senior Engineer"); salary bounds are inclusive.
- History tools default to CURRENT records only. Questions about totals
  over an employment history ("how many salary records/departments/titles
  in total", "joined first") need the FULL history: pass
  from_date=1985-01-01, then count items (or read the earliest row).
- Call submit_answer exactly ONCE — its answer argument is your committed
  answer. Afterwards reply with a short text restating that same answer
  (placeholders are fine) and call no more tools.
- Answer with the requested value only — a number, a name, a date
  (YYYY-MM-DD), true/false, or a department/title name. No explanations,
  no thousands separators, no currency symbols.
"""

_EAG_PROMPT = _BASE_PROMPT + """
## REDACTED MODE
Data tools return STRUCTURE ONLY — you never see raw values. Everything
you saw in an earlier tool result is REFERENCABLE in later tool calls and
in your final answer with {{ }} placeholders; the harness resolves them
locally:
- ids between tools: {"emp_no": "{{ search_employees.items[0].emp_no }}"}
- dates between tools: {"at_date": "{{ get_department_managers[0].from_date }}"}
- numeric filters: {"min_salary": "{{ get_employee.salary }}"}
- Final answer: state values as placeholders, e.g. "{{ get_employee.salary }}"
  or "{{ get_salary_stats[0].avg_salary }}".
- Never invent a literal value you did not choose yourself. If a placeholder
  fails, correct its path and retry.
- A "not found" error means you typed an id: take it from your earlier
  search result and reference it instead.
- A bare tool name references your MOST RECENT call to that tool. Index
  earlier calls explicitly: {{ search_employees[0] }} is the first call,
  {{ search_employees[1] }} the second — e.g. subtracting two search
  totals: compute(a="{{ search_employees[0].total }}",
  b="{{ search_employees[1].total }}").
- Since you cannot see row values, select entities purely through search
  arguments: filter by first_name AND last_name until the result contains
  exactly one item, then reference items[0].

## COMPUTING WITHOUT SEEING VALUES
You cannot compare or combine values in your head — you never saw them.
Use the evaluator tools; they compute locally and you reference the
outcome symbolically:
- True/false questions: compare(left="{{ get_employee.salary }}", op=">=",
  right=64423), then answer "{{ compare.result }}". Ops: == != > >= < <=.
- Differences/sums: compute(a="{{ get_salary_stats[0].avg_salary }}",
  op="-", b=50000) → answer "{{ compute.result }}".
- Join strings (e.g. a full name): concat(parts=[
  "{{ get_top_earners[0].first_name }}",
  "{{ get_top_earners[0].last_name }}"]) → "{{ concat.result }}".
- Count a list: count_items(ref="{{ get_salary_history }}") →
  "{{ count_items.result }}".
- Find a row by field value instead of guessing an index:
  filter_items(ref="{{ get_reference.departments }}", key="dept_name",
  value="Sales") → use "{{ filter_items.matches[0].dept_no }}".
Never answer a comparison by inventing the outcome — always call compare.
"""


@register("employees")
class EmployeesDataset(DatasetABC):
    name = "employees"
    default_max_steps = 16

    def __init__(self):
        self._eag_mode = False

    def load(self, limit: Optional[int] = None) -> list[Task]:
        if not _TASKS_PATH.exists():
            raise FileNotFoundError(
                f"tasks.json not found at {_TASKS_PATH}. "
                "Run: uv run python scripts/generate_employees_questions.py "
                "(requires docker compose up -d)"
            )
        with open(_TASKS_PATH, encoding="utf-8") as f:
            doc = json.load(f)
        tasks = doc["tasks"]
        if limit:
            tasks = tasks[: min(limit, len(tasks))]
        return [
            Task(
                id=t["id"],
                question=t["question"],
                gold_answer=t["gold_answer"],
                context=[],
                metadata={"category": t["category"], **t.get("metadata", {})},
            )
            for t in tasks
        ]

    def make_tools(self, task: Task, eag_mode: bool = False) -> list:
        # Record mode so system_prompt (read next by the runner) matches.
        self._eag_mode = eag_mode
        return make_employees_tools(eag_mode=eag_mode)

    @property
    def system_prompt(self) -> str:
        return _EAG_PROMPT if self._eag_mode else _BASE_PROMPT

    # ── Scoring ────────────────────────────────────────────────────────

    _NUM_RE = re.compile(r"-?\$?\d[\d,]*(?:\.\d+)?")

    @staticmethod
    def _to_float(s: str) -> float | None:
        try:
            return float(s.replace(",", "").replace("$", "").strip())
        except ValueError:
            return None

    def score(self, trajectory, task: Task) -> dict:
        gold = task.gold_answer.strip()
        answer = (trajectory.answer or "").strip()

        # The agent may end its turn with submit_answer and no final text —
        # the submitted argument is the answer (already placeholder-resolved
        # by the EAG middleware mid-run).
        if not answer:
            for step in reversed(trajectory.steps):
                if step.get("type") == "action" and step.get("action") == "submit_answer":
                    submitted = step.get("action_input", {}).get("answer", "")
                    if submitted:
                        answer = submitted.strip()
                        break
        category = task.metadata.get("category", "")

        detail = {"category": category}
        if not answer:
            return {"correct": False, "score": 0.0, "metric": "employees", **detail}

        gold_num = self._to_float(gold)
        if gold_num is not None:
            # Strict: exactly one distinct number in the answer, within
            # tolerance of the gold. Extra numbers make the answer ambiguous
            # and score 0 (verbose answers quoting several values).
            nums = {self._to_float(m.group()) for m in self._NUM_RE.finditer(answer)}
            matched = next(iter(nums)) if len(nums) == 1 else None
            correct = matched is not None and abs(matched - gold_num) <= 0.011
            em = 1.0 if correct else 0.0
            detail.update(matched_number=matched, n_numbers=len(nums))
        elif gold.lower() in ("true", "false"):
            em = exact_match(answer, gold)
            correct = em == 1.0
            detail["matched_boolean"] = normalize_answer(answer)
        else:
            em = exact_match(answer, gold)
            correct = em == 1.0
            detail["matched_string"] = normalize_answer(answer)

        score = em if gold_num is not None else f1_score(answer, gold)
        return {
            "correct": correct,
            "score": score,
            "metric": "employees",
            "em": em,
            "f1": score if gold_num is None else em,
            **detail,
        }
